test("resolveTask: each source's own task, the reader's words, or none", () => {
  assert.equal(resolveTask({ mode: "off", source: { kind: "pr", number: 1 }, pr: { number: 1, title: "T", body: "B" } }), null);
  const own = resolveTask({ mode: "own", own: "  Make it fast  ", source: { kind: "uncommitted" } });
  assert.deepEqual([own.from, own.text, own.label], ["own", "Make it fast", "Your own words"]);
  assert.equal(resolveTask({ mode: "own", own: "   ", source: { kind: "uncommitted" } }), null);

  const pr = resolveTask({ source: { kind: "pr", number: 12 }, pr: { number: 12, title: "Retry uploads", body: "<!-- hint -->\nOn 503 too." } });
  assert.deepEqual([pr.from, pr.label, pr.text], ["pr", "The description of #12", "Retry uploads\n\nOn 503 too."]);
  assert.equal(resolveTask({ source: { kind: "pr", number: 12 }, pr: null }), null); // the list hasn't come yet
  assert.equal(resolveTask({ source: { kind: "pr", number: 12 }, pr: { number: 12, title: "", body: "" } }), null);

  const commit = resolveTask({ source: { kind: "commit", hash: "abc" }, commit: "Add retries\n\nSigned-off-by: A <a@a>" });
  assert.deepEqual([commit.from, commit.text], ["commit", "Add retries"]);
  assert.equal(resolveTask({ source: { kind: "commit", hash: "abc" }, commit: "" }), null);

  const prompts = resolveTask({ source: { kind: "branch", base: "main" }, since: "the branch left main", prompts: [{ at: 1, text: "Add X" }, { at: 2, text: "/clear" }, { at: 3, text: "Also Y" }] });
  assert.equal(prompts.from, "prompts");
  assert.equal(prompts.label, "2 prompts sent to agents since the branch left main");
  assert.equal(prompts.short, "2 prompts");
  assert.equal(prompts.text, "Message 1:\nAdd X\n\nMessage 2:\nAlso Y");
  assert.equal(resolveTask({ source: { kind: "uncommitted" }, prompts: [] }), null);
  assert.equal(resolveTask({ source: { kind: "staged" }, prompts: [{ at: 1, text: "/clear" }] }), null);
  assert.equal(resolveTask({ source: { kind: "unknown" } }), null);
  assert.equal(resolveTask({ source: null }), null);

  // Too long a task is cut to the limit, never refused.
  assert.equal(resolveTask({ mode: "own", own: "z".repeat(MAX_TASK_CHARS * 2), source: { kind: "staged" } }).text.length, MAX_TASK_CHARS);
});

test("a turn's task is its prompt; the session's earlier prompts (only those) make it clear", () => {
  const t = (id, started, session, prompt) => ({ id, started, session, prompt });
  const turns = [t("5", 50, "s1", "Yes, the second one"), t("4", 40, "s1", "Which retry policy?"), t("3", 30, "s2", "Other session"),
    t("2", 20, "s1", "/clear"), t("1", 10, "s1", "Add retries"), t("0", 5, "s1", "Oldest"), t("6", 60, "s1", "Later")];
  const task = resolveTask({ source: { kind: "turn", id: "5", prompt: "Yes, the second one" }, turn: turns[0], turns });
  assert.deepEqual([task.from, task.text], ["turn", "Yes, the second one"]);
  assert.equal(task.context, "Oldest\n\nAdd retries\n\nWhich retry policy?"); // oldest first, at most MAX_CONTEXT
  assert.equal(task.context.split("\n\n").length, MAX_CONTEXT);
  // No session recorded: no context. An empty or command prompt: no task.
  assert.equal(resolveTask({ source: { kind: "turn", id: "x", prompt: "Do it" }, turn: { id: "x", prompt: "Do it" }, turns }).context, "");
  assert.equal(resolveTask({ source: { kind: "turn", id: "x", prompt: "" }, turn: null }), null);
  assert.equal(resolveTask({ source: { kind: "turn", id: "x", prompt: "/compact" }, turn: null }), null);
});

test("cache keys: prompts sent to agents are one kind of task, so another prompt keeps the walkthrough exact", () => {
  const d = buildDigest([{ scope: "working", patch: PATCH }]);
  const base = { top: "/r", source: "uncommitted", model: "haiku", language: "en", files: d.files };
  const prompts = (text) => ({ from: "prompts", text, context: "" });
  assert.equal(taskCacheKey(null), "");
  assert.equal(taskCacheKey(prompts("Add X")), taskCacheKey(prompts("Add X\n\nthanks")));
  assert.equal(cacheKey({ ...base, task: taskCacheKey(prompts("A")) }), cacheKey({ ...base, task: taskCacheKey(prompts("A, then B")) }));
  // Still a key of its own: Off and Found don't share a walkthrough.
  assert.notEqual(cacheKey(base), cacheKey({ ...base, task: taskCacheKey(prompts("A")) }));
  // Any other task is keyed by its words.
  assert.notEqual(taskCacheKey({ from: "own", text: "A" }), taskCacheKey({ from: "own", text: "B" }));
  assert.equal(taskCacheKey({ from: "pr", text: "A" }), taskKey({ from: "pr", text: "A" }));
  // What the walkthrough was matched against is still told apart, for the task page's note.
  assert.notEqual(taskKey(prompts("A")), taskKey(prompts("A, then B")));
});

