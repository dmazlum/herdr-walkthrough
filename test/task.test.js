test("normalize: requests point at real hunks, and their coverage follows the hunks found", () => {
  const d = digest();
  const raw = answer([
    { text: "Swap old for new", hunks: ["h1", "[h1]", "h99"], coverage: "seen" },
    { text: "Greet and space", hunks: ["h3", "h2"], coverage: "partly" },
    { text: "Called seen, nothing found", hunks: ["h77"], coverage: "seen" },
    { text: "Called absent, but names a hunk", hunks: ["h3"], coverage: "absent" },
    { text: "Odd coverage", hunks: ["h1"], coverage: "maybe" },
    { text: "  ", hunks: ["h1"], coverage: "seen" },
    { text: "Document it", hunks: [], coverage: "absent" },
  ]);
  const w = normalize(raw, d.idByAlias, d.digestFiles, { asks: true });
  assert.deepEqual(w.asks.map((a) => [a.id, a.text, a.coverage, a.hunkIds.length]), [
    ["a1", "Swap old for new", "seen", 1], ["a2", "Greet and space", "partly", 2], ["a3", "Called seen, nothing found", "absent", 0],
    ["a4", "Called absent, but names a hunk", "partly", 1], ["a5", "Odd coverage", "seen", 1], ["a6", "Document it", "absent", 0],
  ]);
  // Without a task, whatever the model said about requests is not read.
  assert.equal(normalize(raw, d.idByAlias, d.digestFiles).asks, null);
  // Missing or broken asks with a task: none.
  assert.deepEqual(normalize({ ...raw, asks: "x" }, d.idByAlias, d.digestFiles, { asks: true }).asks, []);
  const many = normalize(answer(Array.from({ length: 30 }, (_, i) => ({ text: `R${i} ${"w".repeat(300)}`, hunks: ["h1"], coverage: "seen" }))), d.idByAlias, d.digestFiles, { asks: true });
  assert.equal(many.asks.length, LIMITS.asks);
  assert.ok(many.asks.every((a) => a.text.length <= LIMITS.askText));
});

test("overlayAsks: steps per request, Not covered, steps outside every request, and what changed since", () => {
  const d = digest();
  const w = normalize(answer([
    { text: "Swap", hunks: ["h1"], coverage: "seen" },
    { text: "Space and greet", hunks: ["h2", "h3"], coverage: "partly" },
    { text: "Docs", hunks: [], coverage: "absent" },
  ]), d.idByAlias, d.digestFiles, { asks: true });
  const view = overlay(w, d.files);
  const tv = overlayAsks(w.asks, view);
  assert.deepEqual(tv.asks.map((a) => [a.text, a.steps.map((s) => s.position), a.tail, a.outdated]), [
    ["Swap", [1], 0, false], ["Space and greet", [2], 1, false], ["Docs", [], 0, false],
  ]);
  assert.deepEqual(tv.outside.map((s) => s.title), ["Extra"]);
  assert.deepEqual([tv.met, tv.total], [2, 3]);
  assert.deepEqual(asksOf(tv, view.steps[1]).map((a) => a.text), ["Space and greet"]);
  assert.deepEqual(asksOf(null, view.steps[0]), []);

  // The first hunk is edited: its request's code is gone, and says so.
  const now = buildDigest([{ scope: "working", patch: PATCH.replace("+new", "+newer") }]).files;
  const later = overlayAsks(w.asks, overlay(w, now));
  assert.deepEqual(later.asks.map((a) => [a.missing, a.outdated, a.steps.length]), [[1, true, 0], [0, false, 1], [0, false, 0]]);

  // Written without a task: nothing. A task with no concrete request: no step is outside it.
  assert.equal(overlayAsks(null, view), null);
  const none = overlayAsks([], view);
  assert.deepEqual([none.outside, none.total, none.met], [[], 0, 0]);
});

test("markdown: the task's requests with their steps; posted, it can be left out", () => {
  const d = digest();
  const w = normalize(answer([
    { text: "Swap", hunks: ["h1"], coverage: "seen" },
    { text: "Greet", hunks: ["h3", "h2"], coverage: "partly" },
    { text: "Docs", hunks: [], coverage: "absent" },
  ]), d.idByAlias, d.digestFiles, { asks: true });
  const view = overlay(w, d.files);
  const md = toMarkdown(view, w, {}, overlayAsks(w.asks, view), "The description of #12");
  assert.match(md, /^<!-- walkthrough -->\n## T/);
  assert.match(md, /<!-- \/walkthrough -->\n$/);
  assert.match(md, /### Task\n\n<sub>The description of #12<\/sub>\n\n- ✓ Swap — step 1\n- ◐ Greet — partly, step 2, Not covered\n- ○ Docs — not in this diff\n\nNot tied to any request: step 3\./);
  assert.ok(md.indexOf("### Task") < md.indexOf("### P"));
  assert.doesNotMatch(toMarkdown(view, w, {}), /### Task/);
  const empty = toMarkdown(view, w, {}, overlayAsks([], view), "");
  assert.match(empty, /### Task\n\n_The task names nothing concrete/);
  assert.doesNotMatch(empty, /Not tied/);
  // What the markdown pastes into a description is left out when that description is read as a task.
  assert.equal(cleanDescription(`Why.\n\n${md}`), "Why.");
});

