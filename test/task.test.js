test("joined prompts: numbered; past the limit the first stays and the newest follow", () => {
  assert.equal(joinMessages([]), "");
  assert.equal(joinMessages([{ text: "Only one" }]), "Only one");
  assert.equal(joinMessages([{ text: "A" }, { text: "B" }]), "Message 1:\nA\n\nMessage 2:\nB");
  const many = Array.from({ length: 30 }, (_, i) => ({ text: `${i === 0 ? "THE TASK" : `refine ${i}`} ${"x".repeat(400)}` }));
  const joined = joinMessages(many);
  assert.ok(joined.length <= MAX_TASK_CHARS, joined.length);
  assert.match(joined, /^Message 1:\nTHE TASK/);
  assert.match(joined, /Message 30:\nrefine 29/);
  assert.match(joined, /\(\d+ messages in between left out\)/);
  // One huge message is cut, not dropped.
  assert.ok(joinMessages([{ text: "y".repeat(10_000) }]).length <= MAX_MESSAGE_CHARS);
});

